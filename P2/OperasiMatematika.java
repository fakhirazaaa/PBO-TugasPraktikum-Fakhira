package praktikum;

public class OperasiMatematika {
    public static void main(String[] args) {
        double x = 22;
        double y = 33;
        
        System.out.println("================================");
        System.out.println("       Operasi Matematika");
        System.out.println("================================");
        System.out.println("Diketahui Bilangan:");
        System.out.println("x = " + x + " dan y = " + y);
        System.out.println("--------------------------------");
        System.out.println("Penjumlahan (x + y) = " + (x + y));
        System.out.println("Pengurangan (x - y) = " + (x - y));
        System.out.println("Perkalian (x * y) = " + (x * y));
        System.out.println("Pembagian (x / y) = " + (x / y));
        System.out.println("=================================");
    }
}
