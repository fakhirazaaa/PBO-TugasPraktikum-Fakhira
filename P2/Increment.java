package praktikum;

public class Increment {
    public static void main(String[] args) {
        int angka = 5;

        System.out.println("Nilai awal: " + angka);
        System.out.println("Hasil ++angka: " + (++angka));
        System.out.println("Hasil angka++: " + (angka++)); 
        System.out.println("Nilai akhir angka: " + angka);  
    }
}
